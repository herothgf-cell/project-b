using System;
using System.Collections.Generic;
using System.Linq;
using UnityEngine;

// The three 40 m NGII records describe the full bridge reserve. In aerial
// imagery the four through lanes and the two outside strips occupy about 32 m.
public static class MayuBridgeShoulders {
    const string Prefix = "37612023:A0020000:";
    static readonly string[] SectionIds = {"1374", "1159", "507", "2125", "2114", "2175", "2147"};
    const float ShoulderRibbonWidth = 8f;

    static float HalfWidth(float z) {
        float south = Mathf.SmoothStep(0, 1, Mathf.InverseLerp(1521, 1566, z));
        float north = Mathf.SmoothStep(0, 1, Mathf.InverseLerp(1685, 1635, z));
        float join = Mathf.Lerp(9.1f, 9.5f, Mathf.InverseLerp(1566, 1635, z));
        return Mathf.Lerp(join, 16f, south * north);
    }

    static MapPoint Point(Vector3 p) { return new MapPoint{x=p.x, z=p.z}; }

    static Vector3 Side(AssistedRoadNetwork.Path path, float at) {
        var tangent = path.Position(Mathf.Min(path.length, at+4)) - path.Position(Mathf.Max(0, at-4));
        return TrafficSystem.Right(tangent.normalized);
    }

    public static void Apply(MapData map) {
        if (map.mapId!="eungye" || map.roads==null) return;
        var sections = SectionIds.Select(id=>Array.Find(map.roads, r=>r.id==Prefix+id+":0")).ToArray();
        if (sections.Any(r=>r==null) || sections.Skip(2).Take(3).Any(r=>Mathf.Abs(r.width-40)>.01f)) return;
        var center = sections.SelectMany(r=>r.points).Where(p=>p.z>=1520 && p.z<=1686)
            .Select(p=>p.V()).Distinct().OrderBy(p=>p.z).ToArray();
        if (center.Length<2) return;
        var path = new AssistedRoadNetwork.Path(center);
        var roads = new List<MapRoad>(map.roads);
        var marks = new List<HdMark>(map.hdMarks??Array.Empty<HdMark>());
        MoveKerbs(map, path, sections);
        foreach (var section in sections.Skip(2).Take(3)) section.width=18.6f;
        foreach (int side in new[]{-1,1}) {
            var ribbon = new List<MapPoint>();
            var innerEdge = new List<MapPoint>();
            var outerEdge = new List<MapPoint>();
            for (float sample=0; sample<path.length+1; sample+=1) {
                float at=Mathf.Min(sample,path.length);
                var p=path.Position(at);
                var normal=Side(path,at)*side;
                float half=HalfWidth(p.z);
                ribbon.Add(Point(p+normal*(half-ShoulderRibbonWidth*.5f)));
                // Allow 3.5 m for the outside lane and 0.5 m at the kerb.
                float outer=half-4f;
                const float inner=8.6f;
                if (outer>inner+.12f) {
                    innerEdge.Add(Point(p+normal*inner));
                    outerEdge.Add(Point(p+normal*outer));
                    if (((int)sample)%4==0 && outer>inner+.45f) {
                        var tip=path.Position(at-side*1.1f);
                        marks.Add(new HdMark{id="mayu:gore:"+side+":"+sample,kind="531",type="211",
                            points=new[]{Point(tip+normal*inner),Point(p+normal*outer)}});
                    }
                }
            }
            roads.Add(new MapRoad{id="mayu:bridge-shoulder:"+side,name="마유로 계수교 측방 포장",width=ShoulderRibbonWidth,
                lanes=1,suppressPaint=true,points=ribbon.ToArray()});
            if (outerEdge.Count>1) {
                marks.Add(new HdMark{id="mayu:gore-inner:"+side,kind="531",type="211",points=innerEdge.ToArray()});
                marks.Add(new HdMark{id="mayu:gore-outer:"+side,kind="531",type="211",points=outerEdge.ToArray()});
            }
        }
        map.roads=roads.ToArray();
        map.hdMarks=marks.ToArray();
        ProjectMapScene.InvalidateAreaIndex(map);
    }

    struct SourceKerb {
        public Vector3 center;
        public float halfWidth;
    }

    static void MoveKerbs(MapData map, AssistedRoadNetwork.Path path, MapRoad[] sections) {
        // Match the exact slab stations generated by RoadSurfaceIndex.Capture.
        var sourceKerbs=new List<SourceKerb>();
        foreach (var section in sections) for (int i=1;i<section.points.Length;i++) {
            var a=section.points[i-1].V();
            var b=section.points[i].V();
            if (Mathf.Max(a.z,b.z)<1515 || Mathf.Min(a.z,b.z)>1698) continue;
            var dir=(b-a).normalized;
            var right=TrafficSystem.Right(dir);
            float half=section.width*.5f;
            float length=(b-a).magnitude;
            for (float at=1.5f;at<length;at+=3) {
                foreach (int sign in new[]{-1,1}) {
                    var station=a+dir*at+sign*right*(half+1);
                    sourceKerbs.Add(new SourceKerb{center=station,halfWidth=half});
                }
            }
        }
        foreach (var area in map.areas??Array.Empty<MapArea>()) {
            if (area.kind!="sidewalk" || area.evidence==null || !area.evidence.StartsWith("sidewalk:generated:")) continue;
            var center=ProjectMapScene.Center(area.points);
            if (center.x<1390 || center.x>1520 || center.z<1515 || center.z>1698) continue;
            var source=sourceKerbs.Find(k=>(k.center-center).sqrMagnitude<.0004f);
            if (source.halfWidth<=0) continue;
            foreach (var p in area.points) {
                var vertex=p.V();
                float at=path.Project(vertex,out _);
                var axis=path.Position(at);
                var normal=Side(path,at);
                float sign=Mathf.Sign(Vector3.Dot(vertex-axis,normal));
                var shift=normal*(sign*(HalfWidth(axis.z)-source.halfWidth));
                p.x+=shift.x;
                p.z+=shift.z;
            }
        }
    }
}
